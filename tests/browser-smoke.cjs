// Optional real-browser smoke test. npm i --no-save playwright, then npx playwright install chromium.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { chromium } = require(process.env.PLAYWRIGHT_PATH || 'playwright');
const base = process.env.TEST_URL || 'http://localhost:4173/preview-repo/';
const server = process.env.TEST_START_SERVER ? require('../server.cjs') : null;
let browser;

(async () => {
  browser = await chromium.launch({ headless: true, ...(process.env.BROWSER_PATH ? { executablePath: process.env.BROWSER_PATH } : {}) });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1100 } });
  const errors = [], failed = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('console', msg => { if (msg.type() === 'error') errors.push(msg.text()); });
  page.on('response', response => { if (response.status() >= 400) failed.push(response.url()); });
  fs.mkdirSync('test-results', { recursive: true });
  await page.goto(base); await page.waitForFunction(() => window.Olivia?.inspect);
  await page.screenshot({ path: 'test-results/desktop-home.png', fullPage: true });
  await page.locator('#start-button').click();
  const before = await page.evaluate(() => Olivia.inspect());
  await page.keyboard.down('ArrowRight'); await page.waitForTimeout(450); await page.keyboard.up('ArrowRight');
  let state = await page.evaluate(() => Olivia.inspect()); assert.ok(state.player.x > before.player.x + 45, 'keyboard moves player');
  await page.keyboard.down('Space'); await page.waitForTimeout(190);
  state = await page.evaluate(() => Olivia.inspect()); assert.ok(state.player.y < 360, 'Space jumps');
  await page.keyboard.up('Space'); await page.waitForTimeout(650);
  await page.keyboard.press('Escape'); assert.equal(await page.evaluate(() => Olivia.inspect().scene), 'paused');
  const frozen = await page.evaluate(() => Olivia.inspect().levelTime); await page.waitForTimeout(150);
  assert.equal(await page.evaluate(() => Olivia.inspect().levelTime), frozen, 'pause freezes world');
  await page.getByRole('button', { name: 'Продолжить приключение', exact: true }).click();
  await page.keyboard.press('KeyR'); state = await page.evaluate(() => Olivia.inspect()); assert.ok(state.player.x <= 101, 'R restarts');
  await page.locator('#help-button').click(); assert.ok(await page.locator('#menu-dialog').evaluate(d => d.open));
  await page.keyboard.press('Escape'); await page.waitForFunction(() => Olivia.inspect().scene === 'playing');
  await page.locator('#outfits-nav').click(); assert.equal(await page.locator('.outfit').count(), 4); await page.locator('#close-dialog').click();
  await page.screenshot({ path: 'test-results/desktop-game.png', fullPage: true });
  await page.locator('#sound-button').click(); assert.equal(await page.locator('#sound-button').getAttribute('aria-pressed'), 'false');
  await page.reload(); assert.equal(await page.locator('#sound-button').getAttribute('aria-pressed'), 'false', 'sound setting persists');
  await page.locator('#worlds-nav').click(); await page.locator('.dialog-world').first().click();
  await page.waitForFunction(() => document.activeElement === document.getElementById('game'));
  await page.keyboard.down('Space'); await page.waitForTimeout(160); await page.keyboard.up('Space');
  assert.ok((await page.evaluate(() => Olivia.inspect().player.y)) < 370, 'jump retains keyboard focus after world chooser');

  const mobile = await browser.newPage({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, deviceScaleFactor: 2 });
  mobile.on('pageerror', e => errors.push(e.message));
  await mobile.goto(base); await mobile.waitForFunction(() => window.Olivia?.inspect);
  assert.ok(await mobile.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), 'mobile has no horizontal overflow');
  await mobile.screenshot({ path: 'test-results/mobile-home.png', fullPage: true });
  const cover = await mobile.locator('#game-frame').boundingBox(), start = await mobile.locator('#start-button').boundingBox();
  assert.ok(start.y + start.height <= cover.y + cover.height, 'start button fits inside mobile cover');
  await mobile.locator('#start-button').tap();
  await mobile.waitForFunction(() => Olivia.inspect().scene === 'playing');
  await mobile.locator('[data-control=jump]').waitFor({ state: 'visible' });
  const right = await mobile.locator('[data-control=right]').boundingBox();
  await mobile.mouse.move(right.x + right.width / 2, right.y + right.height / 2); await mobile.mouse.down();
  await mobile.waitForTimeout(400); await mobile.mouse.up();
  assert.ok((await mobile.evaluate(() => Olivia.inspect().player.x)) > 140, 'pointer control moves player');
  const jump = await mobile.locator('[data-control=jump]').boundingBox();
  await mobile.mouse.move(jump.x + jump.width / 2, jump.y + jump.height / 2); await mobile.mouse.down(); await mobile.waitForTimeout(160);
  assert.ok((await mobile.evaluate(() => Olivia.inspect().player.y)) < 370, 'touch jump works'); await mobile.mouse.up();
  await mobile.screenshot({ path: 'test-results/mobile-game.png', fullPage: true });
  await mobile.setViewportSize({ width: 844, height: 390 }); await mobile.waitForTimeout(150);
  await mobile.screenshot({ path: 'test-results/mobile-landscape.png', fullPage: true });
  assert.equal(await mobile.locator('#game-frame').evaluate(e => getComputedStyle(e).position), 'fixed', 'mobile landscape fills viewport');
  const bounds = await mobile.locator('#game-frame').boundingBox(); assert.ok(bounds.height >= 385 && bounds.height <= 395, 'landscape uses screen height');
  await mobile.setViewportSize({ width: 320, height: 720 }); await mobile.reload();
  const smallCover = await mobile.locator('#game-frame').boundingBox(), smallStart = await mobile.locator('#start-button').boundingBox();
  assert.ok(smallStart.y + smallStart.height <= smallCover.y + smallCover.height, '320px start button is not clipped');
  assert.ok(await mobile.evaluate(() => document.documentElement.scrollWidth <= innerWidth), '320px has no horizontal overflow');

  const direct = await browser.newPage();
  direct.on('pageerror', e => errors.push(e.message));
  await direct.goto(require('node:url').pathToFileURL(path.resolve('index.html')).href);
  await direct.locator('#start-button').click(); assert.equal(await direct.evaluate(() => Olivia.inspect().scene), 'playing', 'direct file launch');
  assert.deepEqual(errors, [], 'no browser errors'); assert.deepEqual(failed, [], 'all relative resources load from subpath');
  console.log('PASS: desktop, keyboard, jump, pause, retry, menus, persistence, mobile pointer controls, landscape, project subpath, file://. No console/network errors.');
  await browser.close();
})().catch(e => { console.error(e); process.exitCode = 1; }).finally(async () => { await browser?.close(); server?.close(); });
